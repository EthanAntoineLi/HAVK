// Build the single-file, offline-ready HTML deliverable.
// Usage: node build.mjs
import * as esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));

// embed the optimised CAD model as base64
const glb = fs.readFileSync(path.join(root, 'model/arm-opt.glb'));
const b64 = glb.toString('base64');
fs.writeFileSync(path.join(root, 'src/modelData.js'), `// generated by build.mjs - do not edit\nexport const ARM_GLB_B64 = ${JSON.stringify(b64)};\n`);

const result = await esbuild.build({
  entryPoints: [path.join(root, 'src/main.js')],
  bundle: true,
  minify: true,
  format: 'iife',
  target: ['chrome100', 'safari15'],
  write: false,
  legalComments: 'none',
  logLevel: 'warning'
});

const js = result.outputFiles[0].text;
const template = fs.readFileSync(path.join(root, 'index.template.html'), 'utf8');
if (!template.includes('<!--APP-->')) throw new Error('template marker missing');
const html = template.replace('<!--APP-->', () => `<script>\n${js}\n</script>`);

const out = path.resolve(root, '..', 'EPQ-Robotic-Arm-3D.html');
fs.writeFileSync(out, html);
console.log(`wrote ${out}  (${(html.length / 1024).toFixed(0)} KB, js ${(js.length / 1024).toFixed(0)} KB)`);
